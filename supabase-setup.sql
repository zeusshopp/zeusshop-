-- 4) REALTIME (live updates for shop catalog, orders, users, inventory)
--    Idempotent: safe to re-run. Adds tables that are not published yet.
-- -------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'skins') then
    alter publication supabase_realtime add table public.skins;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'announcement') then
    alter publication supabase_realtime add table public.announcement;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'orders') then
    alter publication supabase_realtime add table public.orders;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'site_settings') then
    alter publication supabase_realtime add table public.site_settings;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'users') then
    alter publication supabase_realtime add table public.users;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'inventory') then
    alter publication supabase_realtime add table public.inventory;
  end if;
end $$;

-- -------------------------------------------------------------
-- 5) LIVE USER COUNT for the shop hero ("+N کاربران فعال")
--    Run this ONCE. The shop (anonymous client) cannot list the
--    users table (RLS hides it), so we expose a safe count.
-- -------------------------------------------------------------
create or replace function public.count_users()
returns bigint
language sql stable security definer as $$
  select count(*)::bigint from public.users
$$;
revoke execute on function public.count_users() from public, anon, authenticated;
grant execute on function public.count_users() to anon, authenticated;

-- -------------------------------------------------------------
-- 6) COUPON SINGLE-USE (+ایمن: کد تخفیف فقط یک‌بار، برای همه)
--    Anonymous shoppers INSERT their claimed code here; the PRIMARY KEY
--    on "coupon" makes the second claim fail — even while the order is
--    still pending (pending orders are hidden by RLS, so the orders table
--    alone can't stop double-use). Run this ONCE.
-- -------------------------------------------------------------
create table if not exists public.coupon_claims (
  coupon text primary key,
  telegram text not null default '',
  created_at timestamptz not null default now()
);
alter table public.coupon_claims enable row level security;

drop policy if exists "claims public insert" on public.coupon_claims;
drop policy if exists "claims public read"   on public.coupon_claims;
drop policy if exists "claims public delete" on public.coupon_claims;

create policy "claims public insert" on public.coupon_claims
  for insert with check (true);
create policy "claims public read" on public.coupon_claims
  for select using (true);
create policy "claims public delete" on public.coupon_claims
  for delete using (public.is_admin());

-- -------------------------------------------------------------
-- 7) REPAIR (order & users policies) + ANTI-SPAM
--    Run this if any of these happen:
--      • Admin approval shows "در دیتابیس ذخیره نشد"
--      • New orders don't reach the panel / "کاربران فعال" stays 0
--    It re-adds the missing coupon column + RLS policies (safe to re-run),
--    makes "id" a real primary key, and installs the anti-spam guard so a
--    buyer can't flood orders (max 3 pending, min 30s between orders).
-- -------------------------------------------------------------
alter table public.orders add column if not exists coupon text not null default '';

do $$
begin
  if not exists (select 1 from pg_constraint where conrelid = 'public.orders'::regclass and contype = 'p') then
    execute 'alter table public.orders add primary key (id)';
  end if;
  if not exists (select 1 from pg_indexes where schemaname = 'public' and tablename = 'orders' and indexname = 'idx_orders_telegram') then
    execute 'create index idx_orders_telegram on public.orders (telegram)';
  end if;
  if not exists (select 1 from pg_indexes where schemaname = 'public' and tablename = 'orders' and indexname = 'idx_orders_status') then
    execute 'create index idx_orders_status on public.orders (status)';
  end if;
end $$;

-- re-create the ORDERS policies (guarded: never fails even if a leftover exists)
alter table public.orders enable row level security;
do $$
declare p text;
begin
  foreach p in array array['orders public insert','orders public insert guarded','orders public read approved','orders admin read','orders admin change','orders admin delete'] loop
    if exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'orders' and policyname = p) then
      execute format('drop policy %I on public.orders', p);
    end if;
  end loop;
end $$;

create policy "orders public read approved" on public.orders
  for select using (status = 'approved');
create policy "orders admin read" on public.orders
  for select using (public.is_admin());
create policy "orders admin change" on public.orders
  for update using (public.is_admin()) with check (public.is_admin());
create policy "orders admin delete" on public.orders
  for delete using (public.is_admin());

-- anti-spam RPC: allowed = less than 3 pending orders AND last order older than 30s
create or replace function public.checkout_allowed(tg text)
returns boolean language sql stable security definer as $$
  select
    (select count(*) from public.orders where telegram = tg and status = 'pending') < 3
    and (select coalesce(max(date), '-infinity') from public.orders where telegram = tg)
        < now() - interval '30 seconds'
$$;
revoke execute on function public.checkout_allowed(text) from public, anon, authenticated;
grant execute on function public.checkout_allowed(text) to anon, authenticated;

-- orders may ONLY be inserted when the anti-spam check passes
create policy "orders public insert guarded" on public.orders
  for insert with check (public.checkout_allowed(telegram));

-- make sure USERS inserts still reach the DB (active-user counter)

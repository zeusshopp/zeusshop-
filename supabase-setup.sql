-- helper: is the current session an admin?
create or replace function public.is_admin()
returns boolean language sql stable security definer as $$
  select exists (select 1 from public.admins where id = auth.uid())
$$;

-- skins: anyone can view, only admins add/change/delete
create policy "skins public read" on public.skins
  for select using (true);
create policy "skins admin write" on public.skins
  for all using (public.is_admin()) with check (public.is_admin());

-- orders: everyone can place, only admins read/approve/reject, public sees approved
create policy "orders public insert" on public.orders
  for insert with check (true);
create policy "orders public read approved" on public.orders
  for select using (status = 'approved');
create policy "orders admin read" on public.orders
  for select using (public.is_admin());
create policy "orders admin change" on public.orders
  for update using (public.is_admin()) with check (public.is_admin());
create policy "orders admin delete" on public.orders
  for delete using (public.is_admin());

-- inventory: viewable publicly (by telegram), only admins add
create policy "inventory public read" on public.inventory
  for select using (true);
create policy "inventory admin write" on public.inventory
  for all using (public.is_admin()) with check (public.is_admin());

-- users: registration is public, list is admin-only

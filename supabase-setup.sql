-- 1) TABLES
-- -------------------------------------------------------------
create table if not exists public.skins (
  id bigint generated by default as identity primary key,
  name text not null unique,
  img text not null default '',
  weapon text not null default 'Rifle',
  wear text not null default 'Factory New',
  rarity text not null default 'Covert',
  type text not null default 'Normal',
  price numeric(12,2) not null default 0,
  discount int not null default 0,
  sort int not null default 0,
  delivery_mode text not null default 'immediate',
  delivery_days int not null default 0,
  created_at timestamptz not null default now()
);
alter table public.skins add column if not exists delivery_mode text not null default 'immediate';
alter table public.skins add column if not exists delivery_days int not null default 0;

create table if not exists public.orders (
  id bigint primary key,
  telegram text not null,
  items jsonb not null default '[]',
  total numeric(12,2) not null default 0,
  status text not null default 'pending',
  coupon text not null default '',
  date timestamptz not null default now()
);
alter table public.orders add column if not exists coupon text not null default '';
create index if not exists idx_orders_coupon on public.orders (coupon);

create table if not exists public.inventory (
  id bigint generated by default as identity primary key,
  telegram text not null,
  name text not null,
  price numeric(12,2) not null default 0,
  img text not null default '',
  weapon text not null default '',
  wear text not null default '',
  rarity text not null default '',
  type text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists idx_inv_tg on public.inventory (telegram);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  tg text not null unique,
  date timestamptz not null default now()
);

create table if not exists public.announcement (
  id int primary key default 1,
  enabled boolean not null default false,
  text text not null default '',
  constraint announcement_singleton check (id = 1)
);
insert into public.announcement (id, enabled, text)
values (1, false, '')
on conflict (id) do nothing;

create table if not exists public.site_settings (
  key text primary key,
  value text not null default '',
  updated_at timestamptz not null default now()
);

-- Admins = the Auth users allowed to manage the panel.
-- (RLS policies below refuse writes to anyone NOT in this table.)
create table if not exists public.admins (
  id uuid primary key references auth.users (id) on delete cascade
);


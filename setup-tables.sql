-- WHY THIS FILE EXISTS: database.sql only builds RLS policies,
-- functions and defaults — it assumes the base tables already
-- exist (the original project was set up with a separate script
-- that was never kept). This file rebuilds those tables with the
-- EXACT schema the site expects (verified column-by-column
-- against the live database and js/db.js).
--
-- HOW TO USE (new project):
--   1) SQL Editor → New query → paste THIS file → Run
--   2) SQL Editor → New query → paste database.sql → Run
-- Every statement is IF NOT EXISTS / idempotent → safe to re-run.
-- =============================================================

-- products (catalog) — upsert conflicts on NAME (db.js deltaDb),
-- id is never sent by the client → identity default (like the old DB)
create table if not exists public.skins (
  id             bigint generated by default as identity primary key,
  name           text not null,
  img            text not null default '',
  weapon         text not null default 'Rifle',
  wear           text not null default 'Factory New',
  rarity         text not null default 'Covert',
  type           text not null default 'Normal',
  price          bigint not null default 0,
  discount       int    not null default 0,
  sort           int    not null default 0,
  delivery_mode  text   not null default 'immediate',
  delivery_days  int    not null default 0,
  created_at     timestamptz not null default now(),
  float          numeric,
  constraint skins_name_key unique (name)
);

-- orders — id is the client timestamp (Date.now()); `items` is the jsonb
-- array carrying products AND the base64 receipt photo
create table if not exists public.orders (
  id          bigint primary key,
  telegram    text   not null default '',
  items       jsonb  not null default '[]'::jsonb,
  total       bigint not null default 0,
  status      text   not null default 'pending',
  coupon      text   not null default '',
  date        timestamptz not null default now(),
  created_at  timestamptz not null default now()
);

-- per-buyer inventory (filled on approval; id auto like the old DB)
create table if not exists public.inventory (
  id          bigint generated by default as identity primary key,
  telegram    text   not null default '',
  name        text   not null default '',
  price       bigint not null default 0,
  img         text   not null default '',
  weapon      text   not null default '',
  wear        text   not null default '',
  rarity      text   not null default '',
  type        text   not null default '',
  created_at  timestamptz not null default now()
);

-- registered shoppers (telegram telemetry) — unique tg = users_tg_key
-- (db.js matches on that exact constraint name for duplicate detection)
create table if not exists public.users (
  id    bigint generated by default as identity primary key,
  tg    text not null,
  date  timestamptz not null default now(),
  constraint users_tg_key unique (tg)
);

-- single announcement bar (one row, id = 1)
create table if not exists public.announcement (
  id      int  primary key,
  enabled boolean not null default false,
  text    text   not null default ''
);

-- key→value settings (pay card, rules, hero, raffle, ...).
-- value is TEXT (not jsonb!): the client always stores plain strings
-- (saveSetting does String(value)) — JSON payloads arrive already
-- stringified, exactly like the original database.
create table if not exists public.site_settings (
  key        text primary key,
  value      text,
  updated_at timestamptz not null default now()
);

-- server-side single-use coupons (pk = coupon code, see db.js)
create table if not exists public.coupon_claims (
  coupon     text primary key,
  telegram   text not null default '',
  created_at timestamptz not null default now()
);

-- API grants (matches Supabase's own defaults; RLS still guards rows)
grant usage on schema public to anon, authenticated;
grant all on all tables in schema public to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- friendly notice
select 'ZEUSSHOP tables ready — now run database.sql' as result;
